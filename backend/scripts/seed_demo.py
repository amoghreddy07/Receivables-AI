def run_autonomous(db, cc: dict, horizon_days: int = 45) -> None:
    """Replay the real agent loop until the case settles (eval-harness driver,
    same code path the 63-case evaluation uses; the sandbox pays only when the
    executed intervention matches the seeded scenario)."""
    simulate_case(db, cc, _cfg_auto(), horizon_days=horizon_days)


def run_supervised_approval(db, cc: dict) -> None:
    """SUPERVISED demo: park the action for a human, approve it in the audit
    trail, then let the simulated payer settle on their stated date."""
    clock = VirtualClock(start=T0)
    set_clock(clock)

    seed_case(db, cc, T0)
    db.commit()

    # tick -> overdue invoice opens a case -> diagnosis -> action parked
    run_tick(db, _cfg_supervised())
    db.commit()

    case = db.scalar(select(RiskCase).where(RiskCase.case_key == f"invoice:{cc['invoice_id']}"))
    assert case is not None, f"supervised case {cc['invoice_id']} was not opened"
    pending = db.scalars(
        select(Intervention).where(
            Intervention.case_id == case.id, Intervention.status == "PENDING_APPROVAL"
        )
    ).all()
    assert len(pending) == 1, f"expected exactly one parked action, got {len(pending)}"

    res = decide_approval(
        db,
        pending[0].id,
        decision="APPROVED",
        actor="finance-lead@receivablesai.demo",
        reason="Payer confirms invoice approved + queued in AP; light status follow-up authorized",
        cfg=_cfg_supervised(),
    )
    assert res["ok"], f"approval failed: {res}"
    db.commit()

    # advance to the moment the payer's simulated funds arrive, then drain
    inter = db.get(Intervention, pending[0].id)
    due = (inter.outcome or {}).get("pending_payment", {}).get("pending_at")
    assert due, f"approved action produced no simulated payment for {cc['invoice_id']}"
    clock.advance(to=datetime.fromisoformat(due) + timedelta(minutes=1))
    run_tick(db, _cfg_supervised())
    db.commit()


def run_supervised_pending(db, cc: dict) -> None:
    """SUPERVISED demo: park the action for a human and STOP.

    The case stays PENDING_APPROVAL in the demo DB so the dashboard Approvals
    queue has a live item; the human decision happens later through
    decide_approval() (APPROVE -> executor runs the parked action; DECLINE ->
    audited close). The simulated payer's settlement offset is pinned to 0 so
    an APPROVE resolves the case immediately after the decision.
    """
    clock = VirtualClock(start=T0)
    set_clock(clock)

    seed_case(db, cc, T0)
    db.commit()
    run_tick(db, _cfg_supervised())
    db.commit()

    case = db.scalar(select(RiskCase).where(RiskCase.case_key == f"invoice:{cc['invoice_id']}"))
    assert case is not None, f"supervised-pending case {cc['invoice_id']} was not opened"
    pending = db.scalars(
        select(Intervention).where(
            Intervention.case_id == case.id, Intervention.status == "PENDING_APPROVAL"
        )
    ).all()
    assert len(pending) == 1, f"expected exactly one parked action, got {len(pending)}"

    # deterministic world: the payer settles the moment the approved AP-status
    # follow-up executes (offset 0), so the live dashboard approval resolves.
    invoice = db.get(Invoice, case.invoice_id)
    meta = dict(invoice.meta or {})
    meta["scenario_offset_hours"] = 0.0
    invoice.meta = meta
    db.commit()


