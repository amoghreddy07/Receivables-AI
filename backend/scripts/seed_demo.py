"""Deterministic demo-seeding script (dashboard groundwork) — NOT the eval corpus.

Creates (or re-creates) a small curated set of demo cases in a DEDICATED demo
database (default <project>/data/demo.db) through the EXISTING machinery: the
real ORM models, the real agent loop (app.agent), the deterministic policy
engine, the SeededSandbox provider, and the hash-chained audit log.

    python -m scripts.seed_demo [--db-url sqlite:///...]

The 63-case evaluation corpus (app/eval/corpus.py) is untouched. The demo
cases deliberately span the behaviours a dashboard walkthrough needs:

    DEMO-INV-001  docs/GST blocker   -> AI (NLU) reads the email, documentation_fix
                                        playbook is authorized, invoice recovers.
    DEMO-INV-002  AP approval queue  -> AI reads "queued in AP", SUPERVISED mode
                                        parks the action; a human approves it in
                                        the audit trail; invoice recovers on the
                                        payer's stated date.
    DEMO-INV-003  explicit promise   -> AI extracts "15 January 2026", promise is
                                        confirmed + persisted; pays on that date.
    DEMO-INV-004  invoice dispute    -> escalate INVOICE_DISPUTE; no auto-collection.
    DEMO-INV-005  AVS fraud signal   -> deterministic fraud hard-stop; the AI and
                                        customer message cannot unlock a retry.
    DEMO-INV-006  DNC on file        -> deterministic compliance hard-stop.
    DEMO-INV-007  exactly 120 days   -> allowed by the compliance boundary -> recovers.
    DEMO-INV-008  121 days overdue   -> compliance-age hard-stop despite a paying
                                        profile (the rule beats the money).
    DEMO-INV-009  AP release + human  -> parked SUPERVISED and deliberately left
                                        PENDING_APPROVAL so the dashboard Approvals
                                        queue has a live item; Approve/Decline goes
                                        through the real decide_approval() mechanism.

Why this is honest, not theatrical:
  * Ground truth is what the payer's own message literally states.
  * The sandbox pays ONLY when the actually-executed intervention matches the
    seeded situation (profile docs_issue pays on resend_corrected_invoice, the
    ap_queue world on request_ap_update, ptp_offer_will_pay on confirm_ptp, and
    never_pays/flagged worlds never pay) — nothing reads the diagnosis or the
    "AI's reasoning".
  * Fraud / DNC / bankruptcy / >120-day outcomes are produced by deterministic
    policy rules in app/policy/rules.py, never by an LLM.
  * Every recovery and every stop is a real Diagnosis / Intervention / Approval
    / Escalation / AuditEvent row generated by the normal agent loop, all under
    a fixed virtual clock so re-runs are bit-identical.

Idempotency: the script DROPs and re-CREATEs the demo database schema on every
run, so running it twice never duplicates rows and always rebuilds the same
history. Everything in the demo DB is generated state — never source.
"""
