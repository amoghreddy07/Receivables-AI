def _money(inr: int) -> int:
    return inr * 100  # paise (minor units), like the whole codebase


def _demo_case(
    seq: int,
    scenario: str,
    org: str,
    amount_inr: int,
    profile: str,
    *,
    flags: list[str] | None = None,
    due_days_ago: int = 0,
    attempts: list[tuple[str, int, str, str]] | None = None,
    messages: list[dict] | None = None,
    world_offset_hours: float | None = None,
    detection: str = "overdue_tick",
    gt_playbook: str,
    expected_inr: int = 0,
    should_escalate: bool = False,
) -> dict:
    """A demo case in the same shape the eval harness already understands."""
    inv_id = f"DEMO-INV-{seq:03d}"
    return {
        "id": f"demo_{seq:03d}",
        "scenario": scenario,
        "org": org,
        "invoice_id": inv_id,
        "amount_minor": _money(amount_inr),
        "paid_minor": 0,
        "currency": "INR",
        "profile": profile,
        "flags": flags or [],
        "due_days_ago": due_days_ago,
        "attempts": attempts or [],
        "promise_days": None,
        "future_events": [],
        "messages": [
            {
                "direction": "in",
                "channel": m.get("channel", "email"),
                "content": m["content"].replace("$INV", inv_id),
                "days_ago": float(m.get("days_ago", 2.0)),
            }
            for m in (messages or [])
        ],
        "world_offset_hours": world_offset_hours,
        "start_hour": 10,
        "detection": detection,
        "ground_truth": {
            "playbook": gt_playbook,
            "expected_recovery_minor": _money(expected_inr),
            "should_escalate": should_escalate,
        },
    }


