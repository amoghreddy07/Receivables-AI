def _tag_demo_rows(db) -> None:
    """Mark every demo row as demo/simulated so the dashboard can filter and
    the sandbox origin of outcomes is explicit (honesty marker)."""
    invoice_ids = [
        inv.id for inv in db.scalars(select(Invoice)).all()
        if inv.rzr_invoice_id.startswith("DEMO-INV-")
    ]
    for inv in db.scalars(select(Invoice)).all():
        if inv.id in invoice_ids:
            meta = dict(inv.meta or {})
            meta.update({"demo": True, "simulated": True})
            inv.meta = meta
    for cust in db.scalars(select(Customer)).all():
        meta = dict(cust.meta or {})
        if cust.id in {inv.customer_id for inv in db.scalars(select(Invoice)).all() if inv.id in invoice_ids}:
            meta.update({"demo": True})
            cust.meta = meta
    for msg in db.scalars(select(CaseMessage)).all():
        if msg.invoice_id in invoice_ids:
            meta = dict(msg.meta or {})
            meta["demo"] = True
            msg.meta = meta


def _fmt(inr_paise: int) -> str:
    return f"Rs.{inr_paise / 100:,.0f}"


def _report(db) -> None:
    cases = db.scalars(select(RiskCase).order_by(RiskCase.id)).all()
    print(
        f"\n{'case':<14}{'scenario':<28}{'state':<20}{'cause:path':<26}{'recovered':<16}actions"
    )
    total_recovered = 0
    for case in cases:
        invoice = db.get(Invoice, case.invoice_id)
        scenario = ((invoice.meta or {}).get("eval_scenario")) or case.cause
        intervs = db.scalars(
            select(Intervention).where(Intervention.case_id == case.id).order_by(Intervention.id)
        ).all()
        acts = ", ".join(
            f"{i.playbook}/{i.action}:{i.status}" for i in intervs if i.status != "PENDING_APPROVAL"
        ) or "(none - hard stop / escalate)"
        recovered = case.recovered_amount_minor
        total_recovered += recovered
        print(
            f"{case.entity_id:<14}{scenario:<28}{case.state:<20}"
            f"{case.cause + ':' + case.diagnosis_path:<26}{_fmt(recovered):<16}{acts[:110]}"
        )

    blocked = [c for c in cases if c.state in (C.STATE_STOPPED_COMPLIANCE, C.STATE_STOPPED_FRAUD)]
    escalated = [c for c in cases if c.state == C.STATE_ESCALATED]
    recovered_cases = [c for c in cases if c.state == C.STATE_RECOVERED]
    approvals = db.scalars(select(Approval)).all()
    escal_rows = db.scalars(select(Escalation)).all()
    pending_acts = db.scalars(
        select(Intervention).where(Intervention.status == "PENDING_APPROVAL")
    ).all()
    ok, _broken, msg = verify(db)
    print(
        f"\nDemo summary - {len(cases)} cases | {len(recovered_cases)} recovered "
        f"({_fmt(total_recovered)}) | {len(blocked)} deterministic hard-stops | "
        f"{len(escalated)} escalated | {len(approvals)} human approval(s) | "
        f"{len(pending_acts)} pending approval(s) | "
        f"{len(escal_rows)} escalation row(s)"
    )
    print(f"Audit chain: {msg}")
    if not ok:
        raise SystemExit("audit chain verification FAILED after demo seed")


def main() -> None:
    parser = argparse.ArgumentParser(description="Recreate the ReceivablesAI demo database")
    parser.add_argument("--db-url", default=None, help="sqlite URL (default: data/demo.db)")
    args = parser.parse_args()
    db_url = args.db_url
    if not db_url:
        import os

        db_url = os.getenv("RA_DEMO_DB_URL", DEFAULT_DB_URL)

    print(f"Recreating demo database at {db_url}")
    engine = make_engine(db_url)
    from app.models import Base

    Base.metadata.drop_all(engine)  # idempotency: a fresh, duplicate-free history
    init_db(engine)
    db = make_session(engine)

    reset_clock()
    for cc in DEMO_CASES:
        set_clock(VirtualClock(start=T0))
        if cc["scenario"] == SUPERVISED_SCENARIO:
            run_supervised_approval(db, cc)
        elif cc["scenario"] == SUPERVISED_PENDING_SCENARIO:
            run_supervised_pending(db, cc)
        else:
            run_autonomous(db, cc)
        print(f"  seeded {cc['invoice_id']:<14} scenario={cc['scenario']}")

    reset_clock()
    _tag_demo_rows(db)
    db.commit()

    _report(db)
    db.close()


if __name__ == "__main__":
    main()
