SUPERVISED_SCENARIO = "ap_approval_supervised"  # runs through the human-approval driver
SUPERVISED_PENDING_SCENARIO = "ap_release_today_supervised_pending"  # parked for the dashboard


def _cfg_auto() -> AgentConfig:
    return AgentConfig(
        label="receivablesai-demo",
        mode=C.MODE_AUTONOMOUS,
        llm_mode="auto",
        offline_llm=True,  # deterministic NLU stand-in (no API key needed)
        provider=SeededSandbox(),
    )


def _cfg_supervised() -> AgentConfig:
    return AgentConfig(
        label="receivablesai-demo",
        mode=C.MODE_SUPERVISED,
        llm_mode="auto",
        offline_llm=True,
        provider=SeededSandbox(),
    )


